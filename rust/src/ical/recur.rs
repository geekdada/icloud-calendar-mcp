    fn dt(s: &str) -> NaiveDateTime {
        NaiveDateTime::parse_from_str(s, "%Y-%m-%dT%H:%M:%S").unwrap()
    }

    fn dates(rule: &str, seed: &str, start: &str, end: &str) -> Vec<String> {
        let rule = RRule::parse(rule).unwrap();
        let until = rule.until.map(|u| u.to_local_date_time());
        rule_dates(&rule, dt(seed), until, dt(start), dt(end), 10_000)
            .unwrap()
            .into_iter()
            .map(|d| d.format("%Y-%m-%dT%H:%M").to_string())
            .collect()
    }


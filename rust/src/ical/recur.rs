//! RFC 5545 §3.3.10 recurrence-rule iteration over local wall-clock times.
//!
//! Each FREQ period (year, month, week, day, hour, minute, second) is expanded
//! into its candidate instants: the period's days filtered by the BY* day
//! rules, crossed with the time-of-day set, then narrowed by BYSETPOS. COUNT
//! counts every candidate from the seed on (including those before the
//! requested window), so the window never changes which occurrences exist.

use chrono::{Datelike, NaiveDate, NaiveDateTime, NaiveTime, TimeDelta, Timelike, Weekday};

use super::rrule::{Frequency, RRule, WeekdayNum};

/// Upper bound on periods examined for one rule; past it the rule is
/// pathological for the window (e.g. FREQ=SECONDLY across a year) and the
/// caller reports an over-large expansion instead of grinding on.
pub const MAX_PERIODS: u64 = 1_000_000;

/// The rule needed more than [`MAX_PERIODS`] periods to cover the window.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct PeriodLimitExceeded;

/// Instants generated by `rule` from `seed` that fall in `[range_start, range_end)`,
/// at most `max_count` of them, in ascending order.
///
/// `until` is the rule's UNTIL already converted to the seed's wall clock;
/// candidates after it end the series.
pub fn rule_dates(
    rule: &RRule,
    seed: NaiveDateTime,
    until: Option<NaiveDateTime>,
    range_start: NaiveDateTime,
    range_end: NaiveDateTime,
    max_count: usize,
) -> Result<Vec<NaiveDateTime>, PeriodLimitExceeded> {
    let plan = Plan::new(rule, seed);
    let interval = i64::from(rule.interval.max(1));
    let mut out = Vec::new();
    let mut counted: i64 = 0;
    let count_limit = rule.count.map(i64::from);
    if count_limit.is_some_and(|c| c <= 0) {
        return Ok(out);
    }

    let mut step = if rule.count.is_none() { plan.fast_forward_steps(range_start, interval) } else { 0 };
    let mut examined: u64 = 0;
    loop {
        examined += 1;
        if examined > MAX_PERIODS {
            return Err(PeriodLimitExceeded);
        }
        let Some(period) = plan.period(step * interval) else {
            return Ok(out);
        };
        if period.begin >= range_end || until.is_some_and(|u| period.begin > u) {
            return Ok(out);
        }
        for candidate in plan.candidates(&period) {
            if candidate < seed {
                continue;
            }
            if until.is_some_and(|u| candidate > u) || candidate >= range_end {
                return Ok(out);
            }
            counted += 1;
            if count_limit.is_some_and(|c| counted > c) {
                return Ok(out);
            }
            if candidate >= range_start {
                out.push(candidate);
                if out.len() >= max_count {
                    return Ok(out);
                }
            }
        }
        step += 1;
    }
}

/// One FREQ period: the days it spans and, for sub-daily rules, the fixed
/// parts of the time of day.
struct Period {
    begin: NaiveDateTime,
    first_day: NaiveDate,
    day_count: i64,
    fixed_hour: Option<u32>,
    fixed_minute: Option<u32>,
    fixed_second: Option<u32>,
}

/// The rule with RFC 5545 defaults filled in from the seed.
struct Plan<'a> {
    rule: &'a RRule,
    seed: NaiveDateTime,
    by_month: Option<Vec<i32>>,
    by_month_day: Option<Vec<i32>>,
    by_day: Option<Vec<WeekdayNum>>,
}

impl<'a> Plan<'a> {
    fn new(rule: &'a RRule, seed: NaiveDateTime) -> Self {
        let mut by_month = rule.by_month.clone();
        let mut by_month_day = rule.by_month_day.clone();
        let mut by_day = rule.by_day.clone();
        let no_day_rule = rule.by_week_no.is_none()
            && rule.by_year_day.is_none()
            && rule.by_month_day.is_none()
            && rule.by_day.is_none();
        if no_day_rule {
            match rule.freq {
                Frequency::Yearly => {
                    by_month.get_or_insert_with(|| vec![seed.month() as i32]);
                    by_month_day = Some(vec![seed.day() as i32]);
                }
                Frequency::Monthly => by_month_day = Some(vec![seed.day() as i32]),
                Frequency::Weekly => by_day = Some(vec![WeekdayNum { weekday: seed.weekday(), ordinal: None }]),
                _ => {}
            }
        }
        Self { rule, seed, by_month, by_month_day, by_day }
    }

    /// The period `offset` FREQ units after the seed's period.
    fn period(&self, offset: i64) -> Option<Period> {
        let seed = self.seed;
        let whole_days = |first_day: NaiveDate, day_count: i64| Period {
            begin: first_day.and_time(NaiveTime::MIN),
            first_day,
            day_count,
            fixed_hour: None,
            fixed_minute: None,
            fixed_second: None,
        };
        let sub_daily = |begin: NaiveDateTime, minute: bool, second: bool| Period {
            begin,
            first_day: begin.date(),
            day_count: 1,
            fixed_hour: Some(begin.hour()),
            fixed_minute: minute.then(|| begin.minute()),
            fixed_second: second.then(|| begin.second()),
        };
        Some(match self.rule.freq {
            Frequency::Yearly => {
                let year = i32::try_from(i64::from(seed.year()) + offset).ok()?;
                let first = NaiveDate::from_ymd_opt(year, 1, 1)?;
                let next = NaiveDate::from_ymd_opt(year + 1, 1, 1)?;
                whole_days(first, (next - first).num_days())
            }
            Frequency::Monthly => {
                let months = i64::from(seed.year()) * 12 + i64::from(seed.month0()) + offset;
                let year = i32::try_from(months.div_euclid(12)).ok()?;
                let month = u32::try_from(months.rem_euclid(12)).ok()? + 1;
                let first = NaiveDate::from_ymd_opt(year, month, 1)?;
                whole_days(first, i64::from(days_in_month(year, month)?))
            }
            Frequency::Weekly => {
                let start = week_start(seed.date(), self.rule.wkst).checked_add_signed(TimeDelta::try_weeks(offset)?)?;
                whole_days(start, 7)
            }
            Frequency::Daily => whole_days(seed.date().checked_add_signed(TimeDelta::try_days(offset)?)?, 1),
            Frequency::Hourly => {
                let base = seed.date().and_hms_opt(seed.hour(), 0, 0)?;
                sub_daily(base.checked_add_signed(TimeDelta::try_hours(offset)?)?, false, false)
            }
            Frequency::Minutely => {
                let base = seed.date().and_hms_opt(seed.hour(), seed.minute(), 0)?;
                sub_daily(base.checked_add_signed(TimeDelta::try_minutes(offset)?)?, true, false)
            }
            Frequency::Secondly => {
                let base = seed.with_nanosecond(0)?;
                sub_daily(base.checked_add_signed(TimeDelta::try_seconds(offset)?)?, true, true)
            }
        })
    }

    /// Whole periods that can be skipped before the window without changing
    /// which occurrences exist. Only fixed-length frequencies qualify: whole
    /// months or years would shift day-of-month clamping.
    fn fast_forward_steps(&self, range_start: NaiveDateTime, interval: i64) -> i64 {
        let seed = self.seed;
        if range_start <= seed {
            return 0;
        }
        let units = match self.rule.freq {
            Frequency::Secondly => (range_start - seed).num_seconds(),
            Frequency::Minutely => (range_start - seed).num_minutes(),
            Frequency::Hourly => (range_start - seed).num_hours(),
            Frequency::Daily => (range_start.date() - seed.date()).num_days(),
            Frequency::Weekly => {
                (week_start(range_start.date(), self.rule.wkst) - week_start(seed.date(), self.rule.wkst)).num_weeks()
            }
            Frequency::Monthly | Frequency::Yearly => return 0,
        };
        (units / interval - 1).max(0)
    }

    /// Candidate instants of `period`, ascending, after BYSETPOS.
    fn candidates(&self, period: &Period) -> Vec<NaiveDateTime> {
        let rule = self.rule;
        let Some(times) = self.times(period) else {
            return Vec::new();
        };
        let mut out = Vec::new();
        for i in 0..period.day_count {
            let Some(day) = period.first_day.checked_add_signed(TimeDelta::days(i)) else {
                continue;
            };
            if self.day_matches(day) {
                out.extend(times.iter().map(|t| day.and_time(*t)));
            }
        }
        match &rule.by_set_pos {
            Some(positions) if !out.is_empty() => select_positions(&out, positions),
            _ => out,
        }
    }

    /// The period's time-of-day set, or `None` when a fixed part fails its BY filter.
    fn times(&self, period: &Period) -> Option<Vec<NaiveTime>> {
        let rule = self.rule;
        let component = |fixed: Option<u32>, by: &Option<Vec<i32>>, default: u32, max: u32| -> Option<Vec<u32>> {
            match fixed {
                Some(value) => match by {
                    Some(list) if !list.contains(&(value as i32)) => None,
                    _ => Some(vec![value]),
                },
                None => {
                    let mut values: Vec<u32> = match by {
                        Some(list) => list.iter().filter_map(|v| u32::try_from(*v).ok()).filter(|v| *v <= max).collect(),
                        None => vec![default],
                    };
                    values.sort_unstable();
                    values.dedup();
                    Some(values)
                }
            }
        };
        let hours = component(period.fixed_hour, &rule.by_hour, self.seed.hour(), 23)?;
        let minutes = component(period.fixed_minute, &rule.by_minute, self.seed.minute(), 59)?;
        let seconds = component(period.fixed_second, &rule.by_second, self.seed.second(), 59)?;
        let mut times = Vec::with_capacity(hours.len() * minutes.len() * seconds.len());
        for h in &hours {
            for m in &minutes {
                for s in &seconds {
                    if let Some(t) = NaiveTime::from_hms_opt(*h, *m, *s) {
                        times.push(t);
                    }
                }
            }
        }
        Some(times)
    }

    fn day_matches(&self, day: NaiveDate) -> bool {
        let rule = self.rule;
        if let Some(months) = &self.by_month
            && !months.contains(&(day.month() as i32))
        {
            return false;
        }
        if let Some(weeks) = &rule.by_week_no {
            let (week_year, week) = week_number(day, rule.wkst);
            let total = weeks_in_year(week_year, rule.wkst);
            if !weeks.iter().any(|&w| w == week || (w < 0 && total + w + 1 == week)) {
                return false;
            }
        }
        if let Some(year_days) = &rule.by_year_day {
            let ordinal = day.ordinal() as i32;
            let length = if day.leap_year() { 366 } else { 365 };
            if !year_days.iter().any(|&d| d == ordinal || (d < 0 && length + d + 1 == ordinal)) {
                return false;
            }
        }
        if let Some(month_days) = &self.by_month_day {
            let length = days_in_month(day.year(), day.month()).unwrap_or(31) as i32;
            let dom = day.day() as i32;
            if !month_days.iter().any(|&d| d == dom || (d < 0 && length + d + 1 == dom)) {
                return false;
            }
        }
        if let Some(days) = &self.by_day
            && !days.iter().any(|wd| self.weekday_matches(day, wd))
        {
            return false;
        }
        true
    }

    fn weekday_matches(&self, day: NaiveDate, wd: &WeekdayNum) -> bool {
        if day.weekday() != wd.weekday {
            return false;
        }
        let Some(n) = wd.ordinal.filter(|n| *n != 0) else {
            return true;
        };
        let scope_is_month = self.rule.freq == Frequency::Monthly
            || (self.rule.freq == Frequency::Yearly && self.rule.by_month.is_some());
        match (self.rule.freq, scope_is_month) {
            (_, true) => {
                let length = days_in_month(day.year(), day.month()).unwrap_or(31) as i32;
                nth_matches(day.day() as i32, length, n)
            }
            (Frequency::Yearly, false) if self.rule.by_week_no.is_none() => {
                let length = if day.leap_year() { 366 } else { 365 };
                nth_matches(day.ordinal() as i32, length, n)
            }
            _ => true,
        }
    }
}

/// True when the weekday at 1-based `position` (of `length` days) is the
/// `n`th (or `-n`th from the end) of its kind.
fn nth_matches(position: i32, length: i32, n: i32) -> bool {
    if n > 0 { (position - 1) / 7 + 1 == n } else { (length - position) / 7 + 1 == -n }
}

fn select_positions(candidates: &[NaiveDateTime], positions: &[i32]) -> Vec<NaiveDateTime> {
    let len = candidates.len() as i32;
    let mut picked: Vec<NaiveDateTime> = positions
        .iter()
        .filter_map(|&p| {
            let index = if p > 0 { p - 1 } else { len + p };
            (p != 0 && (0..len).contains(&index)).then(|| candidates[index as usize])
        })
        .collect();
    picked.sort_unstable();
    picked.dedup();
    picked
}

fn days_in_month(year: i32, month: u32) -> Option<u32> {
    let first = NaiveDate::from_ymd_opt(year, month, 1)?;
    let next = if month == 12 { NaiveDate::from_ymd_opt(year + 1, 1, 1)? } else { NaiveDate::from_ymd_opt(year, month + 1, 1)? };
    Some((next - first).num_days() as u32)
}

/// The first day of the week (starting on `wkst`) containing `day`.
fn week_start(day: NaiveDate, wkst: Weekday) -> NaiveDate {
    let back = (7 + day.weekday().num_days_from_monday() - wkst.num_days_from_monday()) % 7;
    day - TimeDelta::days(i64::from(back))
}

/// Start of week 1 of `year`: the first `wkst`-based week with at least four
/// days in the year (RFC 5545 BYWEEKNO numbering).
fn week_one_start(year: i32, wkst: Weekday) -> NaiveDate {
    let jan1 = NaiveDate::from_ymd_opt(year, 1, 1).unwrap_or(NaiveDate::MIN);
    let start = week_start(jan1, wkst);
    let days_in_year = 7 - (jan1 - start).num_days();
    if days_in_year >= 4 { start } else { start + TimeDelta::days(7) }
}

fn weeks_in_year(year: i32, wkst: Weekday) -> i32 {
    ((week_one_start(year + 1, wkst) - week_one_start(year, wkst)).num_days() / 7) as i32
}

/// (numbering year, week number) of `day`.
fn week_number(day: NaiveDate, wkst: Weekday) -> (i32, i32) {
    let year = day.year();
    let this_year = week_one_start(year, wkst);
    let next_year = week_one_start(year + 1, wkst);
    if day >= next_year {
        return (year + 1, 1);
    }
    if day < this_year {
        let previous = week_one_start(year - 1, wkst);
        return (year - 1, ((day - previous).num_days() / 7) as i32 + 1);
    }
    (year, ((day - this_year).num_days() / 7) as i32 + 1)
}

